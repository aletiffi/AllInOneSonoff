# PlatformIO extra script: firmware signing for OTA updates
#
# keys/public.key   RSA public key, embedded in the firmware (committed)
# keys/private.key  RSA private key, used to sign the .bin (NEVER committed, keep a backup!)
#
# - If no key exists (and not running in CI) a new 2048 bit key pair is generated.
# - Before the build: $BUILD_DIR/generated/OtaSigningKey.h is created with the public key.
# - After the build: if the private key exists, the signed firmware is written to
#   $BUILD_DIR/firmware.signed.bin and AllInOneSonoff_v<FW_VERSION>.bin (project root).
#   Signed format (ESP8266 core): <bin><signature><uint32 LE signature length>
#
# Without public key the firmware accepts unsigned updates (OTA_SIGNING 0).

import os
import re
import shutil
import struct
import subprocess
import tempfile

Import("env")

PROJECT_DIR = env.subst("$PROJECT_DIR")
BUILD_DIR = env.subst("$BUILD_DIR")
KEYS_DIR = os.path.join(PROJECT_DIR, "keys")
PUBLIC_KEY = os.path.join(KEYS_DIR, "public.key")
PRIVATE_KEY = os.path.join(KEYS_DIR, "private.key")
GEN_DIR = os.path.join(BUILD_DIR, "generated")
HEADER = os.path.join(GEN_DIR, "OtaSigningKey.h")


def log(msg):
    print("[signing] " + msg)


def run(cmd, **kwargs):
    return subprocess.run(cmd, check=True, capture_output=True, **kwargs)


def generate_keys():
    os.makedirs(KEYS_DIR, exist_ok=True)
    run(["openssl", "genrsa", "-out", PRIVATE_KEY, "2048"])
    os.chmod(PRIVATE_KEY, 0o600)
    run(["openssl", "rsa", "-in", PRIVATE_KEY, "-outform", "PEM", "-pubout", "-out", PUBLIC_KEY])
    log("*" * 70)
    log("New signing keys generated in keys/")
    log("BACKUP keys/private.key: without it you can't update the devices via OTA")
    log("*" * 70)


def check_key_pair():
    derived = run(["openssl", "rsa", "-in", PRIVATE_KEY, "-pubout"]).stdout.decode().strip()
    with open(PUBLIC_KEY) as f:
        if f.read().strip() != derived:
            raise SystemExit("[signing] keys/public.key does not match keys/private.key")


def write_header():
    os.makedirs(GEN_DIR, exist_ok=True)
    if os.path.isfile(PUBLIC_KEY):
        with open(PUBLIC_KEY) as f:
            pem = f.read().strip()
        content = ("// Generated by scripts/signing.py, do not edit\n"
                   "#pragma once\n#include <pgmspace.h>\n#define OTA_SIGNING 1\n"
                   "static const char OTA_SIGNING_PUBKEY[] PROGMEM = R\"KEY(\n" + pem + "\n)KEY\";\n")
    else:
        log("WARNING: keys/public.key not found, OTA updates will NOT be verified")
        content = "// Generated by scripts/signing.py, do not edit\n#pragma once\n#define OTA_SIGNING 0\n"
    old = None
    if os.path.isfile(HEADER):
        with open(HEADER) as f:
            old = f.read()
    if old != content:
        with open(HEADER, "w") as f:
            f.write(content)


def firmware_version():
    with open(os.path.join(PROJECT_DIR, "include", "Config.h")) as f:
        m = re.search(r'#define\s+FW_VERSION\s+"([^"]+)"', f.read())
    return m.group(1) if m else "unknown"


def sign_firmware(source, target, env):
    bin_path = str(target[0])
    if "test" in env.GetBuildType():
        # pio test: the .bin is the test program, not a firmware to release
        return
    if not os.path.isfile(PRIVATE_KEY):
        log("keys/private.key not found: firmware NOT signed (OTA updates to signed devices will be refused)")
        return
    with open(bin_path, "rb") as f:
        data = f.read()
    signature = run(["openssl", "dgst", "-sha256", "-sign", PRIVATE_KEY], input=data).stdout

    # Sanity check with the public key embedded in the firmware
    with tempfile.NamedTemporaryFile(delete=False) as sig:
        sig.write(signature)
    try:
        run(["openssl", "dgst", "-sha256", "-verify", PUBLIC_KEY, "-signature", sig.name], input=data)
    finally:
        os.unlink(sig.name)

    signed = data + signature + struct.pack("<I", len(signature))
    signed_path = os.path.join(BUILD_DIR, "firmware.signed.bin")
    with open(signed_path, "wb") as f:
        f.write(signed)
    release = os.path.join(PROJECT_DIR, "AllInOneSonoff_v%s.bin" % firmware_version())
    shutil.copyfile(signed_path, release)
    log("Signed firmware: %s (%d bytes)" % (os.path.relpath(release, PROJECT_DIR), len(signed)))
    check_ota_space(len(signed))


# eagle.flash.1m.ld: the sketch area ends at 0xFB000 (EEPROM sector). During an OTA the new firmware
# is written after the running one, so both must fit (Updater: ESP.getFreeSketchSpace())
SKETCH_AREA = 0xFB000
SECTOR = 4096


def check_ota_space(size):
    running = (size + SECTOR - 1) // SECTOR * SECTOR
    margin = SKETCH_AREA - running - size
    if margin < 0:
        log("WARNING: firmware too big for OTA (%d bytes missing): it can only be flashed by serial" % -margin)
    else:
        log("OTA space margin: %d bytes" % margin)


if shutil.which("openssl") is None:
    log("WARNING: openssl not found, keys can't be generated and the firmware can't be signed")
elif not os.path.isfile(PUBLIC_KEY) and not os.path.isfile(PRIVATE_KEY) and not os.environ.get("CI"):
    generate_keys()
elif os.path.isfile(PUBLIC_KEY) and os.path.isfile(PRIVATE_KEY):
    check_key_pair()

write_header()
env.Append(CPPPATH=[GEN_DIR])
env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", sign_firmware)
